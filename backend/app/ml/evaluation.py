"""Held-out model evaluation, model registry records, and feature explanations.

All values in this module are calculated from a persisted sklearn pipeline and
the deterministic held-out split.  It intentionally contains no LLM calls.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score, precision_score, recall_score, roc_auc_score

from app.ml.features import DATASET_VERSION, FEATURE_COLUMNS
from app.ml.training import RANDOM_SEED, dataset_fingerprint, split_dataset


@dataclass(frozen=True)
class RiskFactor:
    """A model-derived transformed feature contribution for one prediction."""

    transformed_feature: str
    source_feature: str
    feature_value: float
    contribution: float
    attribution_method: str


@dataclass(frozen=True)
class EvaluationResult:
    """Paths and computed metrics produced by one held-out evaluation run."""

    metrics: dict[str, Any]
    evaluation_path: Path
    report_path: Path
    registry_path: Path


def calculate_metrics(y_true: pd.Series | np.ndarray, probabilities: np.ndarray, threshold: float = 0.5) -> dict[str, Any]:
    """Calculate binary metrics from actual labels and model probabilities."""
    labels = np.asarray(y_true, dtype=int)
    scores = np.asarray(probabilities, dtype=float)
    predictions = (scores >= threshold).astype(int)
    labels_present, support_counts = np.unique(labels, return_counts=True)
    class_distribution = {str(label): int(count) for label, count in zip(labels_present, support_counts, strict=True)}
    return {
        "threshold": threshold,
        "precision": float(precision_score(labels, predictions, zero_division=0)),
        "recall": float(recall_score(labels, predictions, zero_division=0)),
        "f1": float(f1_score(labels, predictions, zero_division=0)),
        "accuracy": float(accuracy_score(labels, predictions)),
        "roc_auc": float(roc_auc_score(labels, scores)),
        "confusion_matrix": confusion_matrix(labels, predictions, labels=[0, 1]).tolist(),
        "support_counts": class_distribution,
        "class_distribution": {label: count / len(labels) for label, count in class_distribution.items()},
    }


def _source_feature(transformed_feature: str) -> str:
    raw_name = transformed_feature.split("__", maxsplit=1)[-1]
    if raw_name in FEATURE_COLUMNS:
        return raw_name
    matching_features = [feature for feature in FEATURE_COLUMNS if raw_name.startswith(f"{feature}_")]
    if matching_features:
        return max(matching_features, key=len)
    return raw_name


def explain_prediction(model: Any, features: dict[str, Any], top_n: int = 5) -> list[RiskFactor]:
    """Return top model-derived factors for a prediction, never LLM prose.

    Tree models use sklearn's documented ``feature_importances_`` equivalent;
    linear models use signed coefficients.  Contributions are computed from the
    exact transformed values supplied to the persisted pipeline.
    """
    if top_n < 1:
        raise ValueError("top_n must be at least 1")
    row = pd.DataFrame([{column: features.get(column) for column in FEATURE_COLUMNS}], columns=FEATURE_COLUMNS)
    preprocessor = model.named_steps["preprocessor"]
    classifier = model.named_steps["classifier"]
    transformed = np.asarray(preprocessor.transform(row))[0]
    names = preprocessor.get_feature_names_out()
    if hasattr(classifier, "feature_importances_"):
        weights = np.asarray(classifier.feature_importances_, dtype=float)
        contributions = np.abs(transformed) * weights
        method = "model_native_feature_importance"
    elif hasattr(classifier, "coef_"):
        weights = np.asarray(classifier.coef_, dtype=float)[0]
        contributions = transformed * weights
        method = "linear_model_coefficient"
    else:
        raise ValueError(f"Unsupported classifier for explanation: {type(classifier).__name__}")
    indices = np.argsort(np.abs(contributions))[::-1][:top_n]
    return [
        RiskFactor(
            transformed_feature=str(names[index]),
            source_feature=_source_feature(str(names[index])),
            feature_value=float(transformed[index]),
            contribution=float(contributions[index]),
            attribution_method=method,
        )
        for index in indices
    ]


def _markdown_report(payload: dict[str, Any]) -> str:
    metrics = payload["metrics"]
    lines = [
        f"# Held-Out Evaluation: {payload['model_version']}",
        "",
        "This report is calculated once per explicit evaluation run from the persisted selected model and the untouched synthetic held-out test split. It is not generated by an LLM.",
        "",
        "## Metrics",
        "",
        "| Metric | Value |",
        "| --- | ---: |",
    ]
    lines.extend(f"| {name.replace('_', ' ').title()} | {metrics[name]:.6f} |" for name in ("precision", "recall", "f1", "accuracy", "roc_auc"))
    lines.extend([
        "",
        "## Confusion Matrix",
        "",
        "Rows are actual classes `[0, 1]`; columns are predicted classes `[0, 1]`.",
        "",
        "```text",
        str(metrics["confusion_matrix"]),
        "```",
        "",
        f"Support counts: `{metrics['support_counts']}`",
        f"Class distribution: `{metrics['class_distribution']}`",
        "",
        "## Provenance",
        "",
        f"- Dataset version: `{payload['dataset_version']}`",
        f"- Dataset fingerprint: `{payload['dataset_fingerprint']}`",
        f"- Artifact: `{payload['artifact_path']}`",
        f"- Model type: `{payload['model_type']}`",
    ])
    return "\n".join(lines) + "\n"


def evaluate_held_out_model(frame: pd.DataFrame, artifact_path: Path, metadata_path: Path) -> EvaluationResult:
    """Evaluate the persisted selected model once against the deterministic held-out split.

    This function does not train or choose a model; invoking it is the explicit,
    auditable held-out evaluation event.
    """
    import joblib

    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    model = joblib.load(artifact_path)
    _x_train, _x_validation, x_test, _y_train, _y_validation, y_test = split_dataset(frame)
    probabilities = model.predict_proba(x_test)[:, 1]
    metrics = calculate_metrics(y_test, probabilities)
    artifact_dir = artifact_path.parent
    evaluation_path = artifact_dir / f"{metadata['model_version']}.evaluation.json"
    report_path = artifact_dir / f"{metadata['model_version']}.evaluation.md"
    registry_path = artifact_dir / f"{metadata['model_version']}.registry.json"
    payload = {
        "model_version": metadata["model_version"],
        "model_type": metadata["model_type"],
        "evaluated_at": datetime.now(UTC).isoformat(),
        "dataset_version": DATASET_VERSION,
        "dataset_fingerprint": dataset_fingerprint(frame),
        "split": {"strategy": "stratified", "random_seed": RANDOM_SEED, "held_out_test_fraction": 0.2, "row_count": len(y_test)},
        "artifact_path": str(artifact_path.resolve()),
        "feature_schema": FEATURE_COLUMNS,
        "metrics": metrics,
    }
    evaluation_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    report_path.write_text(_markdown_report(payload), encoding="utf-8")
    registry = {
        "model_version": metadata["model_version"],
        "model_type": metadata["model_type"],
        "dataset_version": DATASET_VERSION,
        "dataset_fingerprint": payload["dataset_fingerprint"],
        "feature_schema": FEATURE_COLUMNS,
        "artifact_path": payload["artifact_path"],
        "training_metadata_path": str(metadata_path.resolve()),
        "evaluation_path": str(evaluation_path.resolve()),
        "evaluation_report_path": str(report_path.resolve()),
        "metrics": metrics,
    }
    registry_path.write_text(json.dumps(registry, indent=2), encoding="utf-8")
    return EvaluationResult(metrics=metrics, evaluation_path=evaluation_path, report_path=report_path, registry_path=registry_path)
